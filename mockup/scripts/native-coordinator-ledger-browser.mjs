import assert from 'node:assert/strict';
import { createInterface } from 'node:readline';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
const lines = createInterface({ input: process.stdin })[Symbol.asyncIterator]();
const config = JSON.parse((await lines.next()).value);
const browser = await chromium.launch({ executablePath: process.env.HAGENCY_BROWSER_CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
await mkdir(config.output, { recursive: true });
try {
  const context = await browser.newContext({ serviceWorkers: 'block', viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage(); const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  await context.route('**/*', async route => {
    if (new URL(route.request().url()).origin !== config.base) { failures.push('unexpected external request'); await route.abort(); }
    else await route.continue();
  });
  await page.goto(config.url);
  await page.locator('[data-native-state="ready"][aria-busy="false"]').waitFor();
  await page.goto(`${config.base}/console/server-engagements/`);
  await page.getByText('RefusedVisible', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Allocate resource', exact: true }).count(), 0);
  await page.goto(`${config.base}/console/resources/?resource_id=${config.resource}`);
  assert.equal(await page.locator('[data-server-engagements]').count(), 0);
  await page.getByRole('link', { name: 'New resource configuration', exact: true }).click();
  await page.locator('#configuration-engagement option', { hasText: 'example.test' }).waitFor({ state: 'attached' });
  await page.locator('#configuration-engagement').selectOption(config.fleet);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  assert.equal(await page.locator('#configuration-ceiling').count(), 0);
  await page.locator('#wz-tokens').fill('3000');
  await page.getByLabel('Eligible Matrix project managers').fill('@owner:example.test');
  await page.getByRole('button', { name: 'Create resource', exact: true }).click();
  const saved = page.locator('[data-configuration-action="saved"] a'); await saved.waitFor();
  const created = new URL(await saved.getAttribute('href'), config.base).searchParams.get('resource_id');
  assert.notEqual(created, config.resource);
  await page.goto(`${config.base}/console/server-engagements/`);
  const row = page.locator('tr').filter({ has: page.locator(`a[href="/console/resources/new/?resource_id=${created}"]`) });
  await row.waitFor(); assert.match(await row.textContent(), /3,000/);
  assert.equal(await page.getByRole('button', { name: 'Allocate resource', exact: true }).count(), 0);
  await row.getByRole('link', { name: 'Edit configuration', exact: true }).click();
  await page.locator(`[data-native-configuration-id="${created}"]`).waitFor();
  assert.equal(await page.locator('#configuration-engagement').isDisabled(), true);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('#wz-tokens').fill('4000');
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await page.locator('[data-configuration-action="saved"]').waitFor();
  await page.goto(`${config.base}/console/server-engagements/`);
  await row.waitFor(); assert.match(await row.textContent(), /4,000/);
  await page.screenshot({ path: join(config.output, 'server-engagement-ledger.png'), fullPage: true });
  await page.goto(`${config.base}/console/resources/?resource_id=${created}`);
  await page.locator('[data-engagement-resource]').waitFor();
  assert.equal(await page.locator('[data-budget="remaining"]').innerText(), '4,000');
  await page.screenshot({ path: join(config.output, 'resource-shared-ledger.png'), fullPage: true });
  await page.goto(`${config.base}/console/engagements/`);
  await page.getByRole('heading', { name: 'Agent allocations', exact: true }).waitFor();
  await page.getByText('RefusedVisible', { exact: false }).waitFor();
  await page.getByText('project_unavailable', { exact: true }).waitFor();
  await page.screenshot({ path: join(config.output, 'agent-delivered-refusal.png'), fullPage: true });
  const settledRow=page.locator('tr[data-engagement-row]').filter({ hasText: 'SettlementVisible' });
  await settledRow.getByText('Final usage settlement', { exact: true }).click();
  await settledRow.getByLabel('Final consumed tokens').fill('0');
  await settledRow.getByLabel('Accounting reference (no secrets)').fill('Never-started fixture reconciled');
  await settledRow.getByRole('button', { name: 'Confirm final usage and release unused tokens', exact: true }).click();
  await settledRow.locator('[data-settlement-result]').waitFor();
  assert.match(await settledRow.locator('[data-settlement-result]').textContent(), /unused tokens returned 200/);
  await page.screenshot({ path: join(config.output, 'owner-final-usage-settlement.png'), fullPage: true });
  await page.goto(`${config.base}/console/server-engagements/`);
  await page.getByRole('button', { name: 'Change delegation', exact: true }).click();
  await page.locator('[data-engagement-delegation]').getByRole('combobox').selectOption('suspended');
  await page.getByRole('button', { name: 'Save delegation', exact: true }).click();
  await page.getByText('Delegation saved locally. Synchronization with Palpo is queued.', { exact: true }).waitFor();
  await page.screenshot({ path: join(config.output, 'owner-delegation-suspended.png'), fullPage: true });
  assert.deepEqual(failures, []);
  await writeFile(join(config.output, 'report.json'), JSON.stringify({ passed: true, scope: 'Real native console router and domain writer; seeded registration/resource/decision fixture',
    checks: ['single New resource configuration entry creates model and engagement budget atomically', 'no allocation dialog on Resources or Server engagements', 'edit uses the same configuration form', 'Resources displays usable budget rather than a second pool', 'delivered refusal is visible before agent admission', 'Agent allocations label is distinct from server engagements', 'owner reconciles final usage after cleanup and returns only unused tokens', 'owner suspends delegation through the real console and queues its revision'] }, null, 2));
  await context.close();
} finally { await browser.close(); }
